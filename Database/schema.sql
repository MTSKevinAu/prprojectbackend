-- 对比同一个 dailyno 下不同 inputtype 的所有其他字段是否相等
DROP FUNCTION IF EXISTS public.get_patientdetails_field_differences();

CREATE OR REPLACE FUNCTION public.get_patientdetails_field_differences()
RETURNS TABLE
(
    dailyno           varchar(255),
    inputtype_a       integer,
    inputtype_b       integer,
    all_fields_equal  boolean,
    differing_fields  text[]
)
LANGUAGE sql
AS $$
WITH pair AS (
    SELECT
        r1.dailyno,
        r1.inputtype AS inputtype_a,
        r2.inputtype AS inputtype_b,
        r1.payload AS payload_a,
        r2.payload AS payload_b
    FROM
    (
        SELECT
            pd.dailyno,
            pd.inputtype,
            to_jsonb(pd) - 'dailyno' - 'inputtype' - 'userid' AS payload
        FROM public.patientdetails AS pd
        WHERE pd.inputtype = 1
    ) AS r1
    FULL OUTER JOIN
    (
        SELECT
            pd.dailyno,
            pd.inputtype,
            to_jsonb(pd) - 'dailyno' - 'inputtype' - 'userid' AS payload
        FROM public.patientdetails AS pd
        WHERE pd.inputtype = 2
    ) AS r2
        ON r2.dailyno = r1.dailyno
    WHERE r1.dailyno IS NOT NULL OR r2.dailyno IS NOT NULL
)
SELECT
    p.dailyno,
    COALESCE(p.inputtype_a, 1) AS inputtype_a,
    COALESCE(p.inputtype_b, 0) AS inputtype_b,
    p.payload_b IS NOT NULL
        AND cardinality(differences.differing_fields) = 0 AS all_fields_equal,
    CASE
        WHEN p.payload_b IS NULL THEN ARRAY['all']::text[]
        ELSE differences.differing_fields
    END AS differing_fields
FROM pair AS p
CROSS JOIN LATERAL
(
    SELECT COALESCE(
        array_agg(field_difference.field_name ORDER BY field_difference.field_name),
        ARRAY[]::text[]
    ) AS differing_fields
    FROM
    (
        SELECT COALESCE(a_field.key, b_field.key) AS field_name
        FROM jsonb_each(COALESCE(p.payload_a, '{}'::jsonb)) AS a_field
        FULL JOIN jsonb_each(COALESCE(p.payload_b, '{}'::jsonb)) AS b_field
            ON b_field.key = a_field.key
        WHERE a_field.value IS DISTINCT FROM b_field.value
    ) AS field_difference
) AS differences
ORDER BY p.dailyno;
$$;

