    p_target_system text DEFAULT 'LIS',
    p_sequence_date date DEFAULT CURRENT_DATE,
    p_formtypes text[] DEFAULT ARRAY['DR']::text[],
    p_statuses text[] DEFAULT ARRAY['Matched']::text[],
    p_source_table text DEFAULT 'patientdetails_final'
)
RETURNS TABLE
(
    dailyno varchar(255),
    formtype varchar(2),
    centreid varchar(255)
)
LANGUAGE plpgsql
VOLATILE
AS $$
BEGIN
    IF p_target_system IS NULL OR btrim(p_target_system) = '' THEN
        RAISE EXCEPTION 'p_target_system cannot be empty';
    END IF;

    IF p_sequence_date IS NULL THEN
        RAISE EXCEPTION 'p_sequence_date cannot be NULL';
    END IF;

    IF p_source_table IS NULL
       OR p_source_table NOT IN ('patientdetails', 'patientdetails_final') THEN
        RAISE EXCEPTION 'p_source_table must be patientdetails or patientdetails_final';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.patientdetails_duplicates AS duplicate
        WHERE duplicate.sequence_date = p_sequence_date
                    AND (p_formtypes IS NULL OR duplicate.source_formtype = ANY(p_formtypes))
          AND duplicate.source_table = p_source_table
    ) THEN
        RAISE EXCEPTION 'Cannot generate centreid: duplicate records exist for sequence_date %, formtype %, source_table %',
            p_sequence_date, COALESCE(p_formtypes::text, 'ALL'), p_source_table;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.patientdetails_dailyno_gaps AS gap
        WHERE gap.sequence_date = p_sequence_date
                    AND (p_formtypes IS NULL OR gap.formtype = ANY(p_formtypes))
          AND gap.source_table = p_source_table
    ) THEN
        RAISE EXCEPTION 'Cannot generate centreid: dailyno gaps exist for sequence_date %, formtype %, source_table %',
            p_sequence_date, COALESCE(p_formtypes::text, 'ALL'), p_source_table;
    END IF;

    RETURN QUERY
    WITH filtered AS
    (
        SELECT
            pf.dailyno,
            pf.formtype,
            CASE pf.formtype
                WHEN 'DC' THEN 'MC'
                WHEN 'DR' THEN 'MR'
                ELSE pf.formtype
            END AS export_centre_prefix,
            CASE
                WHEN substring(pf.dailyno FROM char_length(pf.formtype) + 1 FOR 6) ~ '^[0-9]{6}$'
                THEN to_date(
                    substring(pf.dailyno FROM char_length(pf.formtype) + 1 FOR 6),
                    'YYMMDD'
                )
            END AS sequence_date,
            COALESCE(
                to_char(pf.datereceived, 'YYMM'),
                CASE
                    WHEN substring(pf.dailyno FROM char_length(pf.formtype) + 1 FOR 4) ~ '^[0-9]{4}$'
                    THEN substring(pf.dailyno FROM char_length(pf.formtype) + 1 FOR 4)
                END
            ) AS export_year_month
        FROM public.patientdetails_final AS pf
        WHERE pf.status = ANY(p_statuses)
    ),
    numbered AS
    (
        SELECT
            filtered.*,
            row_number() OVER (
                PARTITION BY filtered.formtype, export_centre_prefix, export_year_month
                ORDER BY filtered.dailyno
            ) AS export_centre_sequence
        FROM filtered
        ),
    updated AS
    (
        UPDATE public.patientdetails_final AS pf
        SET centreid = numbered.export_centre_prefix || numbered.export_year_month || '-'
                       || lpad(numbered.export_centre_sequence::text, 5, '0')
        FROM numbered
        WHERE pf.dailyno = numbered.dailyno
          AND pf.formtype IS NOT DISTINCT FROM numbered.formtype
          AND numbered.sequence_date = p_sequence_date
          AND numbered.export_year_month IS NOT NULL
          AND (p_formtypes IS NULL OR numbered.formtype = ANY(p_formtypes))
        RETURNING pf.dailyno, pf.formtype, pf.centreid
    ),
    queued AS
    (
        INSERT INTO public.patientdetails_sync
        (
            target_system, centreid, formtype, sequence_date
        )
        SELECT p_target_system, updated.centreid, updated.formtype, p_sequence_date
        FROM updated
        WHERE updated.centreid IS NOT NULL
        ON CONFLICT ON CONSTRAINT ux_patientdetails_sync_target_patient DO NOTHING
        RETURNING id
    )
    SELECT updated.dailyno, updated.formtype, updated.centreid
    FROM updated;
END;
$$;

