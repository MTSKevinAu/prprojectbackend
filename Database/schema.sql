-- 根据 dailyno 获取 patientdetails，支持按 formtype/inputtype/userid 进一步过滤
DROP FUNCTION IF EXISTS public.get_patientdetails_by_dailyno(
    varchar, varchar, integer, integer
);

CREATE OR REPLACE FUNCTION public.get_patientdetails_by_dailyno(
    p_dailyno   varchar(255),
    p_formtype  varchar(2) DEFAULT NULL,
    p_inputtype integer DEFAULT NULL,
    p_userid    integer DEFAULT NULL
)
RETURNS SETOF public.patientdetails
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_dailyno IS NULL OR btrim(p_dailyno) = '' THEN
        RAISE EXCEPTION 'p_dailyno cannot be empty';
    END IF;

    RETURN QUERY
    SELECT pd.*
    FROM public.patientdetails AS pd
    WHERE pd.dailyno = btrim(p_dailyno)
      AND (p_formtype IS NULL OR pd.formtype IS NOT DISTINCT FROM nullif(btrim(p_formtype), ''))
      AND (p_inputtype IS NULL OR pd.inputtype IS NOT DISTINCT FROM p_inputtype)
      AND (p_userid IS NULL OR pd.userid IS NOT DISTINCT FROM p_userid)
    ORDER BY pd.formtype, pd.inputtype, pd.userid;
END;
$$;

