    p_gestationalweek     integer DEFAULT NULL,
    p_gestationalday      integer DEFAULT NULL,
    p_pregnancy           varchar(255) DEFAULT NULL,
    p_ethnicorigin        varchar(255) DEFAULT NULL,
    p_formtype            varchar(2) DEFAULT NULL,
    p_inputtype           integer DEFAULT NULL,
    p_userid              integer DEFAULT NULL,
    p_dailyno             varchar(255) DEFAULT NULL,
    p_centreid            varchar(255) DEFAULT NULL,
    p_productcode         text[] DEFAULT NULL,
    p_ivf                 integer DEFAULT NULL,
    p_redo                text DEFAULT NULL,
    p_hxofabortion        integer DEFAULT NULL,
    p_hold                integer DEFAULT NULL,
    p_tbc                 integer DEFAULT NULL
)
RETURNS TABLE
(
    result_status text,
    result_data public.patientdetails
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_result      public.patientdetails;
    v_match_count integer;
    v_dailyno     varchar(255);
    v_formtype    varchar(2);
BEGIN
    v_dailyno := NULLIF(btrim(p_dailyno), '');
    v_formtype := NULLIF(btrim(p_formtype), '');

    IF v_dailyno IS NULL THEN
        RAISE EXCEPTION 'p_dailyno cannot be empty';
    END IF;

    IF v_formtype IS NULL THEN
        RAISE EXCEPTION 'p_formtype cannot be empty';
    END IF;

    IF p_inputtype IS NULL THEN
        RAISE EXCEPTION 'p_inputtype cannot be empty';
    END IF;

    IF p_userid IS NULL THEN
        RAISE EXCEPTION 'p_userid cannot be empty';
    END IF;

    PERFORM 1
    FROM public.patientdetails AS pd
    WHERE pd.dailyno = v_dailyno
      AND pd.formtype IS NOT DISTINCT FROM v_formtype
      AND pd.inputtype IS NOT DISTINCT FROM p_inputtype
      AND pd.userid IS NOT DISTINCT FROM p_userid
    FOR UPDATE;

    GET DIAGNOSTICS v_match_count = ROW_COUNT;

    IF v_match_count = 0 THEN
        result_status := 'not_found';
        result_data := NULL;
        RETURN NEXT;
        RETURN;
    ELSIF v_match_count > 1 THEN
        result_status := 'multiple_matches';
        result_data := NULL;
        RETURN NEXT;
        RETURN;
    END IF;

        DELETE FROM public.patientdetails_final AS pf
        WHERE pf.dailyno = v_dailyno
            AND pf.formtype IS NOT DISTINCT FROM v_formtype
            AND pf.userid IS NOT DISTINCT FROM p_userid;

    UPDATE public.patientdetails AS pd
        SET centreid = NULLIF(btrim(p_centreid), ''),
                patientnameen = p_patientnameen,
                patientnamechi = p_patientnamechi,
                gender = p_gender,
                dateofbirth = p_dateofbirth,
                age = p_age,
                hkidno = p_hkidno,
                passportno = p_passportno,
                mobile = p_mobile,
                refcustordr = p_refcustordr,
                patientrefno = p_patientrefno,
                billtocustordr = p_billtocustordr,
                speciment = p_speciment,
                remarks = p_remarks,
                datereceived = p_datereceived,
                datecollected = p_datecollected,
                gestationalweek = p_gestationalweek,
                gestationalday = p_gestationalday,
                pregnancy = p_pregnancy,
                ethnicorigin = p_ethnicorigin,
                productcode = p_productcode,
                ivf = p_ivf,
                redo = p_redo,
                hxofabortion = p_hxofabortion,
                hold = p_hold,
                tbc = p_tbc
        WHERE pd.dailyno = v_dailyno
            AND pd.formtype IS NOT DISTINCT FROM v_formtype
            AND pd.inputtype IS NOT DISTINCT FROM p_inputtype
            AND pd.userid IS NOT DISTINCT FROM p_userid
    RETURNING pd.* INTO v_result;

        PERFORM public.sync_patientdetails_final_by_dailyno(v_dailyno);

    result_status := 'updated';
    result_data := v_result;
    RETURN NEXT;
END;
$$;

