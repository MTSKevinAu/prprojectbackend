    varchar(255)
);

CREATE OR REPLACE FUNCTION public.sync_patientdetails_final_by_dailyno(
    p_dailyno varchar(255)
)
RETURNS TABLE
(
    result_status text,
    copied_dailyno varchar(255)
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_row_1 public.patientdetails;
    v_row_2 public.patientdetails;
BEGIN
    IF p_dailyno IS NULL OR btrim(p_dailyno) = '' THEN
        result_status := 'invalid_dailyno';
        copied_dailyno := NULL;
        RETURN NEXT;
        RETURN;
    END IF;

    SELECT *
    INTO v_row_1
    FROM public.patientdetails
    WHERE dailyno = btrim(p_dailyno)
      AND inputtype = 1
    LIMIT 1;

    SELECT *
    INTO v_row_2
    FROM public.patientdetails
    WHERE dailyno = btrim(p_dailyno)
      AND inputtype = 2
    LIMIT 1;

    IF v_row_1 IS NULL OR v_row_2 IS NULL THEN
        result_status := 'no_pair_inputtype_1_2';
        copied_dailyno := p_dailyno;
        RETURN NEXT;
        RETURN;
    END IF;

    -- 比较：除 inputtype 和 userid 之外的字段是否完全相同
    IF (to_jsonb(v_row_1) - 'inputtype' - 'userid') = (to_jsonb(v_row_2) - 'inputtype' - 'userid') THEN
        IF EXISTS (
            SELECT 1
            FROM public.patientdetails_final AS pf
            WHERE pf.dailyno = v_row_1.dailyno
              AND pf.formtype IS NOT DISTINCT FROM v_row_1.formtype
              AND pf.userid IS NOT DISTINCT FROM v_row_1.userid
        ) THEN
            result_status := 'already exists';
            copied_dailyno := v_row_1.dailyno;
            RETURN NEXT;
            RETURN;
        END IF;

        INSERT INTO public.patientdetails_final
        (
            centreid,
            dailyno,
            patientnameen,
            patientnamechi,
            gender,
            dateofbirth,
            age,
            hkidno,
            passportno,
            mobile,
            refcustordr,
            patientrefno,
            billtocustordr,
            speciment,
            remarks,
            datereceived,
            datecollected,
            gestationalweek,
            gestationalday,
            pregnancy,
            ethnicorigin,
            formtype,
            userid,
            productcode,
            ivf,
            redo,
            hxofabortion,
            hold,
            tbc
        )
        VALUES
        (
            v_row_1.centreid,
            v_row_1.dailyno,
            v_row_1.patientnameen,
            v_row_1.patientnamechi,
            v_row_1.gender,
            v_row_1.dateofbirth,
            v_row_1.age,
            v_row_1.hkidno,
            v_row_1.passportno,
            v_row_1.mobile,
            v_row_1.refcustordr,
            v_row_1.patientrefno,
            v_row_1.billtocustordr,
            v_row_1.speciment,
            v_row_1.remarks,
            v_row_1.datereceived,
            v_row_1.datecollected,
            v_row_1.gestationalweek,
            v_row_1.gestationalday,
            v_row_1.pregnancy,
            v_row_1.ethnicorigin,
            v_row_1.formtype,
            v_row_1.userid,
            v_row_1.productcode,
            v_row_1.ivf,
            v_row_1.redo,
            v_row_1.hxofabortion,
            v_row_1.hold,
            v_row_1.tbc
        );

        result_status := 'inserted';
        copied_dailyno := v_row_1.dailyno;
        RETURN NEXT;
        RETURN;
    ELSE
        result_status := 'not_equal_except_inputtype';
        copied_dailyno := p_dailyno;
        RETURN NEXT;
        RETURN;
    END IF;
END;
$$;

-- 根据 dailyno 获取上一条或下一条 patientdetails
DROP FUNCTION IF EXISTS public.get_adjacent_patientdetails(
    varchar, varchar, varchar, integer, integer
);

CREATE OR REPLACE FUNCTION public.get_adjacent_patientdetails(
    p_dailyno   varchar(255),
    p_direction varchar(10), -- 'previous' 或 'next'
    p_formtype  varchar(2) DEFAULT NULL,
    p_inputtype integer DEFAULT NULL,
    p_userid    integer DEFAULT NULL
)
RETURNS SETOF public.patientdetails
LANGUAGE plpgsql
AS $$
DECLARE
    v_direction text := lower(btrim(p_direction));
BEGIN
    IF p_dailyno IS NULL OR btrim(p_dailyno) = '' THEN
        RAISE EXCEPTION 'p_dailyno cannot be empty';
    END IF;

    IF v_direction IS NULL OR v_direction NOT IN ('previous', 'next') THEN
        RAISE EXCEPTION 'p_direction must be previous or next';
    END IF;

    IF v_direction = 'previous' THEN
        RETURN QUERY
        SELECT pd.*
        FROM public.patientdetails AS pd
        WHERE pd.dailyno < btrim(p_dailyno)
          AND (
              NULLIF(btrim(p_formtype), '') IS NULL
              OR pd.formtype = NULLIF(btrim(p_formtype), '')
          )
          AND (p_inputtype IS NULL OR pd.inputtype = p_inputtype)
          AND (p_userid IS NULL OR pd.userid = p_userid)
        ORDER BY
            pd.dailyno DESC,
            pd.formtype DESC NULLS LAST,
            pd.inputtype DESC NULLS LAST,
            pd.userid DESC NULLS LAST
        LIMIT 1;
    ELSE
        RETURN QUERY
        SELECT pd.*
        FROM public.patientdetails AS pd
        WHERE pd.dailyno > btrim(p_dailyno)
          AND (
              NULLIF(btrim(p_formtype), '') IS NULL
              OR pd.formtype = NULLIF(btrim(p_formtype), '')
          )
          AND (p_inputtype IS NULL OR pd.inputtype = p_inputtype)
          AND (p_userid IS NULL OR pd.userid = p_userid)
        ORDER BY
            pd.dailyno ASC,
            pd.formtype ASC NULLS LAST,
            pd.inputtype ASC NULLS LAST,
            pd.userid ASC NULLS LAST
        LIMIT 1;
    END IF;
END;
$$;


