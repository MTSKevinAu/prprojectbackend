    p_patientnamechi      varchar(255) DEFAULT NULL,
    p_gender              varchar(255) DEFAULT NULL,
    p_dateofbirth        date DEFAULT NULL,
    p_age                 integer DEFAULT NULL,
    p_hkidno              varchar(255) DEFAULT NULL,
    p_passportno          varchar(255) DEFAULT NULL,
    p_mobile              varchar(255) DEFAULT NULL,
    p_refcustordr         varchar(255) DEFAULT NULL,
    p_patientrefno        varchar(255) DEFAULT NULL,
    p_billtocustordr      varchar(255) DEFAULT NULL,
    p_speciment           varchar(255) DEFAULT NULL,
    p_remarks             varchar(255) DEFAULT NULL,
    p_datereceived        timestamp without time zone DEFAULT LOCALTIMESTAMP,
    p_datecollected       timestamp without time zone DEFAULT NULL,
    p_gestationalweek     integer DEFAULT NULL,
    p_gestationalday      integer DEFAULT NULL,
    p_pregnancy           varchar(255) DEFAULT NULL,
    p_ethnicorigin        varchar(255) DEFAULT NULL,
    p_formtype            varchar(2) DEFAULT NULL,
    p_inputtype           integer DEFAULT NULL,
    p_userid              integer DEFAULT NULL,
    p_dailyno             varchar(255) DEFAULT NULL,
    p_centreid            varchar(255) DEFAULT NULL,
    p_productcode          text[] DEFAULT NULL,
    p_ivf                 integer DEFAULT NULL,
    p_redo                text DEFAULT NULL,
    p_hxofabortion        integer DEFAULT NULL,
    p_hold                integer DEFAULT NULL,
    p_tbc                 integer DEFAULT NULL
)
RETURNS TABLE
(
    result_status text,
    result_data public.patientdetails
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_formtype    text;
    v_base_time   timestamp without time zone;
    v_centre_seq  integer;
    v_daily_seq   integer;
    v_centre_id   varchar(255);
    v_daily_no    varchar(255);
    v_requested_dailyno varchar(255);
    v_result      public.patientdetails;
BEGIN
    v_formtype := nullif(btrim(p_formtype), '');
    v_centre_id := NULLIF(btrim(p_centreid), '');

    IF v_formtype IS NULL THEN
        RAISE EXCEPTION 'formtype cannot be empty';
    END IF;

    IF length(v_formtype) > 2 THEN
        RAISE EXCEPTION 'formtype must be at most 2 characters';
    END IF;

    IF p_userid IS NULL THEN
        RAISE EXCEPTION 'userid cannot be empty';
    END IF;

    IF p_inputtype IS NULL THEN
        RAISE EXCEPTION 'inputtype cannot be empty';
    END IF;

    v_base_time := COALESCE(p_datereceived, LOCALTIMESTAMP);

    IF p_dailyno IS NOT NULL AND btrim(p_dailyno) <> '' THEN
        IF btrim(p_dailyno) ~ '^[0-9]{4}$' THEN
            v_daily_seq := btrim(p_dailyno)::integer;
        ELSIF btrim(p_dailyno) ~ ('^' || v_formtype || '[0-9]{10}$') THEN
            v_daily_seq := substring(btrim(p_dailyno) FROM length(v_formtype) + 7 FOR 4)::integer;
            v_requested_dailyno := btrim(p_dailyno);
        ELSE
            RAISE EXCEPTION 'p_dailyno must be 4 digits or a complete dailyno';
        END IF;
    ELSIF p_dailyno IS NOT NULL THEN
        RAISE EXCEPTION 'p_dailyno cannot be empty';
    ELSE
        SELECT COALESCE(MAX(
            substring(existing.dailyno FROM length(v_formtype) + 6 + 1 FOR 4)::integer
        ), 0) + 1
        INTO v_daily_seq
        FROM public.patientdetails AS existing
        WHERE existing.dailyno LIKE v_formtype || to_char(v_base_time, 'YYMMDD') || '%'
          AND substring(existing.dailyno FROM length(v_formtype) + 6 + 1 FOR 4) ~ '^[0-9]{4}$';
    END IF;

    v_daily_no := COALESCE(
        v_requested_dailyno,
        v_formtype || to_char(v_base_time, 'YYMMDD') || lpad(v_daily_seq::text, 4, '0')
    );

        SELECT existing.*
        INTO v_result
        FROM public.patientdetails AS existing
        WHERE existing.dailyno IS NOT DISTINCT FROM v_daily_no
            AND existing.formtype IS NOT DISTINCT FROM v_formtype
            AND existing.inputtype IS NOT DISTINCT FROM p_inputtype
            AND existing.userid IS NOT DISTINCT FROM p_userid
        LIMIT 1;

        IF FOUND THEN
            result_status := 'already exists';
            result_data := NULL;
            RETURN NEXT;
            RETURN;
    END IF;

    BEGIN
        INSERT INTO public.patientdetails
        (
            centreid, dailyno, patientnameen, patientnamechi, gender,
            dateofbirth, age, hkidno, passportno, mobile, refcustordr,
            patientrefno, billtocustordr, speciment, remarks, datereceived,
            datecollected, gestationalweek, gestationalday, pregnancy,
            ethnicorigin, formtype, inputtype, userid, productcode,
            ivf, redo, hxofabortion, hold, tbc
        )
        VALUES
        (
            v_centre_id,
            v_daily_no,
            p_patientnameen, p_patientnamechi, p_gender, p_dateofbirth,
            p_age, p_hkidno, p_passportno, p_mobile, p_refcustordr,
            p_patientrefno, p_billtocustordr, p_speciment, p_remarks,
            v_base_time, p_datecollected, p_gestationalweek,
            p_gestationalday, p_pregnancy, p_ethnicorigin, v_formtype,
            p_inputtype, p_userid, p_productcode, p_ivf, p_redo,
            p_hxofabortion, p_hold, p_tbc
        )
        RETURNING * INTO v_result;

        PERFORM public.sync_patientdetails_final_by_dailyno(v_daily_no);

        result_status := 'inserted';
        result_data := v_result;
        RETURN NEXT;
        RETURN;
    EXCEPTION
        WHEN unique_violation THEN
            result_status := 'already exists';
            result_data := NULL;
            RETURN NEXT;
            RETURN;
    END;
END;
$$;

