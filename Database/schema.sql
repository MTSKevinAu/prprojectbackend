CREATE OR REPLACE FUNCTION public.get_next_patientdetails(
    p_formtype     varchar(2),
    p_inputtype    integer,
    p_userid       integer,
    p_datereceived timestamp without time zone DEFAULT LOCALTIMESTAMP,
    p_dailyno      varchar(255) DEFAULT NULL,
    p_centreid     varchar(255) DEFAULT NULL
)
RETURNS SETOF public.patientdetails
LANGUAGE plpgsql
AS $$
DECLARE
    v_formtype  text;
    v_base_time timestamp without time zone;
    v_centre_no integer;
    v_daily_no  integer;
    v_centre_id varchar(255);
    v_dailyno_id varchar(255);
    v_requested_dailyno varchar(255);
    v_existing_record public.patientdetails;
BEGIN
    v_formtype := nullif(btrim(p_formtype), '');
    v_base_time := COALESCE(p_datereceived, LOCALTIMESTAMP);
    v_centre_id := NULLIF(btrim(p_centreid), '');

    IF v_formtype IS NULL THEN
        RAISE EXCEPTION 'formtype cannot be empty';
    END IF;

    IF p_userid IS NULL THEN
        RAISE EXCEPTION 'userid cannot be empty';
    END IF;

    IF p_inputtype IS NULL THEN
        RAISE EXCEPTION 'inputtype cannot be empty';
    END IF;

    IF p_dailyno IS NOT NULL AND btrim(p_dailyno) <> '' THEN
        IF btrim(p_dailyno) ~ '^[0-9]{4}$' THEN
            v_daily_no := btrim(p_dailyno)::integer;
        ELSIF btrim(p_dailyno) ~ ('^' || v_formtype || '[0-9]{10}$') THEN
            v_daily_no := substring(btrim(p_dailyno) FROM length(v_formtype) + 7 FOR 4)::integer;
            v_requested_dailyno := btrim(p_dailyno);
        ELSE
            RAISE EXCEPTION 'p_dailyno must be 4 digits or a complete dailyno';
        END IF;
    ELSIF p_dailyno IS NOT NULL THEN
        RAISE EXCEPTION 'p_dailyno cannot be empty';
    ELSE
        SELECT COALESCE(MAX(
                substring(existing.dailyno FROM length(v_formtype) + 6 + 1 FOR 4)::integer
        ), 0) + 1
        INTO v_daily_no
        FROM public.patientdetails AS existing
        WHERE existing.dailyno LIKE v_formtype || to_char(v_base_time, 'YYMMDD') || '%'
            AND existing.inputtype = p_inputtype
            AND substring(existing.dailyno FROM length(v_formtype) + 6 + 1 FOR 4) ~ '^[0-9]{4}$';
    END IF;

    v_dailyno_id := COALESCE(
        v_requested_dailyno,
        v_formtype || to_char(v_base_time, 'YYMMDD') || lpad(v_daily_no::text, 4, '0')
    );

    SELECT existing.*
    INTO v_existing_record
    FROM public.patientdetails AS existing
         WHERE (existing.centreid = v_centre_id
                 OR existing.dailyno = v_dailyno_id)
             AND existing.formtype IS NOT DISTINCT FROM v_formtype
             AND existing.inputtype IS NOT DISTINCT FROM p_inputtype
             AND existing.userid IS NOT DISTINCT FROM p_userid
    LIMIT 1;

    IF FOUND THEN
        RETURN NEXT v_existing_record;
    ELSE
        v_existing_record := NULL;
        v_existing_record.centreid := v_centre_id;
        v_existing_record.dailyno := v_dailyno_id;
        RETURN NEXT v_existing_record;
    END IF;

    RETURN;
END;
$$;

-- 清空 patientdetails 和 patientdetails_final；必须显式确认
DROP FUNCTION IF EXISTS public.reset_patientdetails(boolean);

CREATE OR REPLACE FUNCTION public.reset_patientdetails(
    p_confirm boolean
)
RETURNS TABLE
(
    patientdetails_deleted bigint,
    patientdetails_final_deleted bigint
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_patientdetails_deleted bigint;
    v_patientdetails_final_deleted bigint;
BEGIN
    IF p_confirm IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Reset cancelled: pass TRUE to confirm deleting all rows';
    END IF;

    DELETE FROM public.patientdetails_final;
    GET DIAGNOSTICS v_patientdetails_final_deleted = ROW_COUNT;

    DELETE FROM public.patientdetails;
    GET DIAGNOSTICS v_patientdetails_deleted = ROW_COUNT;

    patientdetails_deleted := v_patientdetails_deleted;
    patientdetails_final_deleted := v_patientdetails_final_deleted;
    RETURN NEXT;
END;
$$;

