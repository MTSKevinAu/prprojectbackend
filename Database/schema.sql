CREATE OR REPLACE FUNCTION public.get_latest_patientdetails_sync_batch(
    p_target_system text DEFAULT NULL
)
RETURNS TABLE
(
    batch_id bigint,
    target_system text,
    batch_status text,
    batch_started_at timestamp with time zone,
    batch_completed_at timestamp with time zone,
    history_id bigint,
    sync_id bigint,
    centreid varchar(255),
    dailyno varchar(255),
    formtype varchar(2),
    payload jsonb,
    sync_status text,
    created_at timestamp with time zone,
    attempted_at timestamp with time zone,
    completed_at timestamp with time zone,
    synced_at timestamp with time zone,
    remote_record_id text,
    last_http_status integer,
    last_error text
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_target_system IS NOT NULL AND btrim(p_target_system) = '' THEN
        RAISE EXCEPTION 'p_target_system cannot be empty';
    END IF;

    RETURN QUERY
    WITH latest_batch AS (
        SELECT b.*
        FROM public.patientdetails_sync_batches AS b
        WHERE b.completed_at IS NOT NULL
        ORDER BY b.completed_at DESC, b.id DESC
        LIMIT 1
    ),
    latest_attempts AS (
        SELECT DISTINCT ON (h.sync_id) h.*
        FROM public.patientdetails_sync_history AS h
        INNER JOIN latest_batch AS b ON b.id = h.batch_id
        WHERE p_target_system IS NULL OR h.target_system = p_target_system
        ORDER BY h.sync_id, h.id DESC
    )
    SELECT
        b.id,
        h.target_system,
        b.batch_status,
        b.started_at,
        b.completed_at,
        h.id,
        h.sync_id,
        s.centreid,
        (
            SELECT pf.dailyno
            FROM public.patientdetails_final AS pf
            WHERE pf.centreid = s.centreid
              AND pf.formtype = s.formtype
        ),
        s.formtype,
        h.payload,
        h.sync_status,
        h.created_at,
        h.attempted_at,
        h.completed_at,
        h.synced_at,
        h.remote_record_id,
        h.last_http_status,
        h.last_error
    FROM latest_batch AS b
    INNER JOIN latest_attempts AS h ON h.batch_id = b.id
    INNER JOIN public.patientdetails_sync AS s ON s.id = h.sync_id
    ORDER BY h.target_system, h.id;
END;
$$;

