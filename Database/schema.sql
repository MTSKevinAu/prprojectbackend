CREATE OR REPLACE FUNCTION public.get_patientdetails_sync_by_date(
    p_start_date date,
    p_end_date date
)
RETURNS TABLE
(
    id bigint,
    target_system text,
    centreid varchar(255),
    formtype varchar(2),
    dailyno varchar(255),
    sync_status varchar(20),
    attempt_count integer,
    remote_record_id text,
    last_http_status integer,
    last_error text
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_start_date IS NULL OR p_end_date IS NULL THEN
        RAISE EXCEPTION 'p_start_date and p_end_date cannot be NULL';
    END IF;

    IF p_start_date > p_end_date THEN
        RAISE EXCEPTION 'p_start_date cannot be later than p_end_date';
    END IF;

    RETURN QUERY
    SELECT q.id, q.target_system, q.centreid, q.formtype, p.dailyno,
           q.sync_status, q.attempt_count, q.remote_record_id,
           q.last_http_status, q.last_error
    FROM public.patientdetails_sync AS q
    JOIN public.patientdetails_sync_rules AS r
      ON r.formtype = q.formtype
     AND r.target_system = q.target_system
     AND r.is_enabled = true
    JOIN public.patientdetails_final AS p
      ON p.centreid = q.centreid AND p.formtype = q.formtype
    WHERE EXISTS (
        SELECT 1
        FROM generate_series(
            p_start_date::timestamp,
            p_end_date::timestamp,
            INTERVAL '1 day'
        ) AS dates(sequence_date)
        WHERE substring(p.dailyno FROM char_length(p.formtype) + 1 FOR 6)
                = to_char(dates.sequence_date, 'YYMMDD')
    )
      AND p.status = 'Matched'
    ORDER BY q.centreid, q.formtype, q.target_system, q.id;
END;
$$;

